CREATE TABLE usage_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id VARCHAR(36) NOT NULL, layer VARCHAR(24) NOT NULL, source VARCHAR(150) NOT NULL,
  method VARCHAR(16) NOT NULL, host VARCHAR(253) NOT NULL, status INTEGER NOT NULL,
  reason VARCHAR(120) NOT NULL, duration_ms BIGINT NOT NULL, created_at VARCHAR(40) NOT NULL
);
CREATE INDEX usage_events_request ON usage_events(request_id, id DESC);
CREATE INDEX usage_events_layer_status ON usage_events(layer, status);
