package com.apiintel.connectors;

import com.apiintel.integrations.ConnectionService;
import com.apiintel.integrations.IntegrationService;
import com.apiintel.store.RecordStore;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.JsonNodeFactory;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.springframework.stereotype.Service;

/**
 * GitHub read helpers plus the reviewed-write path used by connector codegen:
 * {@link #proposeConnectorPr} stores an approval event whose action carries the
 * whole PR plan (branch, files, title); on execution this service replays the
 * Git Data API sequence (ref → blobs → tree → commit → ref → pull) on the
 * requesting user's own GitHub connection. Generated code is never loaded at
 * runtime — it only exists inside the pull request.
 */
@Service
public class GithubService implements IntegrationService.PersonalConnectionExecutor {

  /** Marker path stored on the approval action; the body holds the full plan. */
  public static final String PR_ACTION_PATH = "/connector-pull-request";

  private static final JsonNodeFactory J = JsonNodeFactory.instance;

  private final RecordStore store;
  private final ConnectionService connections;
  private final IntegrationService integrations;

  public GithubService(RecordStore store, ConnectionService connections,
      IntegrationService integrations) {
    this.store = store;
    this.connections = connections;
    this.integrations = integrations;
  }

  /**
   * Propose a connector PR: action path is the marker, body carries
   * {repo, base, branch, title, body, files:[{path,content}]}.
   */
  public ObjectNode proposeConnectorPr(String connectionId, ObjectNode input,
                                       com.fasterxml.jackson.databind.node.ArrayNode files,
                                       String username) {
    var connection = connections.getOwned(connectionId, username);
    if (!"github".equals(connection.path("provider").asText())) {
      throw new IllegalArgumentException("Select a GitHub connection for the pull request");
    }
    String repo = input.path("repo").asText("");
    if (!repo.matches("[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+")) {
      throw new IllegalArgumentException("Enter the target repo as owner/name");
    }
    String base = input.path("base").asText("main").replaceAll("[^A-Za-z0-9_./-]", "");
    String branch = input.path("branch").asText("").replaceAll("[^A-Za-z0-9_./-]", "");
    if (branch.isBlank()) throw new IllegalArgumentException("Branch name required");
    var action = store.parse("{}").put("method", "POST").put("path", PR_ACTION_PATH);
    var body = store.parse("{}");
    body.put("repo", repo).put("base", base).put("branch", branch);
    body.put("title", input.path("title").asText("Generated connector"));
    body.put("body", input.path("body").asText("Generated by Connection Studio"));
    body.set("files", files);
    action.set("body", body);
    var runtime = connections.runtimeConfig(connection);
    return integrations.propose(runtime, connectionId, action, username);
  }

  @Override
  public boolean supports(ObjectNode event, ObjectNode config) {
    return "github".equals(config.path("provider").asText())
        && PR_ACTION_PATH.equals(event.path("action").path("path").asText())
        && config.path("ownerId").isTextual()
        && !config.path("ownerId").asText().isBlank();
  }

  /** Executes the approved PR plan via the Git Data API on the user's connection. */
  @Override
  public JsonNode execute(ObjectNode event, ObjectNode connection, String actor) {
    if (!actor.equals(event.path("owner").asText(""))
        || !actor.equals(event.path("requester").asText(""))) {
      throw new org.springframework.security.access.AccessDeniedException(
          "This approval belongs to another user");
    }
    connections.assertOwner(connection, actor);
    if (!"CONNECTED".equals(connection.path("state").asText(""))) {
      throw new IllegalArgumentException("Reconnect required before executing this approval");
    }
    var runtime = connections.runtimeConfig(connection);
    var plan = event.path("action").path("body");
    String repo = plan.path("repo").asText();
    String base = plan.path("base").asText("main");
    String branch = plan.path("branch").asText();

    event.put("status", "EXECUTING");
    event = store.save("events", event, actor);
    try {
      JsonNode ref = integrations.call(runtime, "GET",
          "/repos/" + repo + "/git/ref/heads/" + base, null, actor);
      String baseSha = ref.path("object").path("sha").asText();
      var treeItems = J.arrayNode();
      for (JsonNode f : plan.path("files")) {
        var blobReq = J.objectNode()
            .put("content", f.path("content").asText()).put("encoding", "utf-8");
        JsonNode blob = integrations.call(runtime, "POST",
            "/repos/" + repo + "/git/blobs", blobReq, actor);
        treeItems.addObject().put("path", f.path("path").asText())
            .put("mode", "100644").put("type", "blob")
            .put("sha", blob.path("sha").asText());
      }
      var treeReq = J.objectNode().put("base_tree", baseSha);
      treeReq.set("tree", treeItems);
      JsonNode tree = integrations.call(runtime, "POST",
          "/repos/" + repo + "/git/trees", treeReq, actor);
      var commitReq = J.objectNode()
          .put("message", plan.path("title").asText());
      commitReq.putArray("parents").add(baseSha);
      commitReq.put("tree", tree.path("sha").asText());
      JsonNode commit = integrations.call(runtime, "POST",
          "/repos/" + repo + "/git/commits", commitReq, actor);
      var refReq = J.objectNode()
          .put("ref", "refs/heads/" + branch)
          .put("sha", commit.path("sha").asText());
      integrations.call(runtime, "POST", "/repos/" + repo + "/git/refs", refReq, actor);
      var prReq = J.objectNode()
          .put("title", plan.path("title").asText())
          .put("head", branch).put("base", base)
          .put("body", plan.path("body").asText(""));
      JsonNode pr = integrations.call(runtime, "POST",
          "/repos/" + repo + "/pulls", prReq, actor);
      event.put("status", "COMPLETED");
      store.save("events", event, actor);
      return pr;
    } catch (RuntimeException failure) {
      event.put("status", "FAILED");
      store.save("events", event, actor);
      throw failure;
    }
  }
}
