  @Test
  void chatSendPersistsAndSurvivesRestart() {
    server.stubFor(post(urlEqualTo("/chat")).willReturn(okJson("{\"answer\":\"hello there\"}")));
    var ai = aiConnection("alice", "Stylus A");
    assertEquals("CONNECTED", ai.path("state").asText());

    var providers = chat.providers("alice");
    assertEquals(1, providers.size());
    assertEquals(ai.path("id").asText(), providers.get(0).path("connectionId").asText());
    assertEquals("chat", providers.get(0).path("capabilities").path("mode").asText());

    var conv = chat.createConversation(store.parse("{}")
      .put("connectionId", ai.path("id").asText()), "alice");
    String convId = conv.path("id").asText();
    var preview = chat.preview(convId, store.parse("{}").put("prompt", "hi"), "alice");
    assertEquals("localhost", preview.path("destination").asText());
    String confirmation = preview.path("confirmationId").asText();
    assertFalse(confirmation.isBlank());

    var events = collect(chat.send(convId, store.parse("{}")
      .put("prompt", "hi").put("confirmationId", confirmation), "alice"));
    var names = events.stream().map(ServerSentEvent::event).toList();
    assertEquals("meta", names.get(0));
    assertTrue(names.contains("delta"));
    assertEquals("done", names.get(names.size() - 1));
    var deltas = events.stream().filter(e -> "delta".equals(e.event()))
      .map(e -> e.data().path("text").asText()).toList();
    assertEquals(List.of("hello there"), deltas);

    // Second send without preview must fail confirmation.
    assertThrows(ResponseStatusException.class, () -> collect(chat.send(convId,
      store.parse("{}").put("prompt", "again").put("confirmationId", "bogus"), "alice")));

    // Simulate a restart: rebuild services on the same database.
    var chat2 = new ChatService(db, store, users, connections, integrations, chatAdapters,
      contexts, new ConfirmationGrants(), refresher);
    var messages = chat2.messages(convId, "alice");
    assertEquals(2, messages.size());
    assertEquals("hello there", String.valueOf(messages.get(1).get("CONTENT") == null
      ? messages.get(1).get("content") : messages.get(1).get("CONTENT")));

    // Rename + delete + isolation.
    chat2.renameConversation(convId, store.parse("{}").put("title", "Renamed"), "alice");
    assertEquals("Renamed", chat2.conversations("alice").get(0).get("title"));
    assertThrows(ResponseStatusException.class, () -> chat2.messages(convId, "bob"));
    chat2.deleteConversation(convId, "alice");
    assertTrue(chat2.conversations("alice").isEmpty());
  }

  @Test
  void providerSwitchRequiresHistoryTransferConfirmation() {
    server.stubFor(post(urlEqualTo("/chat")).willReturn(okJson("{\"answer\":\"r1\"}")));
    var aiA = aiConnection("alice", "Stylus A");
    var aiB = aiConnection("alice", "Stylus B");
    var conv = chat.createConversation(store.parse("{}")
      .put("connectionId", aiA.path("id").asText()), "alice");
    String convId = conv.path("id").asText();
    var preview = chat.preview(convId, store.parse("{}").put("prompt", "first"), "alice");
    collect(chat.send(convId, store.parse("{}").put("prompt", "first")
      .put("connectionId", aiA.path("id").asText())
      .put("confirmationId", preview.path("confirmationId").asText()), "alice"));

    // Switch without transferHistory → 409.
    assertThrows(ResponseStatusException.class, () -> chat.send(convId, store.parse("{}")
      .put("prompt", "second").put("connectionId", aiB.path("id").asText())
      .put("confirmationId", "x"), "alice"));

    // With transferHistory, preview returns the history and send succeeds.
    var switchPreview = chat.preview(convId, store.parse("{}")
      .put("prompt", "second").put("connectionId", aiB.path("id").asText())
      .put("transferHistory", true), "alice");
    assertTrue(switchPreview.path("historyTransfer").size() > 0);
    var events = collect(chat.send(convId, store.parse("{}")
      .put("prompt", "second").put("connectionId", aiB.path("id").asText())
      .put("transferHistory", true)
      .put("confirmationId", switchPreview.path("confirmationId").asText()), "alice"));
    assertEquals("done", events.get(events.size() - 1).event());
  }

