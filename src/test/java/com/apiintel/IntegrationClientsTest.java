  @Test
  void aiApiKeyAndOAuth() {
    config.put("authType", "API_KEY");
    config.put("headerName", "x-api-key");
    server.stubFor(
      post(urlEqualTo("/v1/messages"))
        .withHeader("x-api-key", equalTo("mock-secret"))
        .willReturn(okJson("{\"content\":[]}"))
    );
    assertTrue(
      service
        .call(config, "POST", "/v1/messages", store.parse("{}"), "test")
        .has("content")
    );
    config.put("authType", "OAUTH2_CLIENT");
    config.put("clientId", "client");
    server.stubFor(
      post(urlEqualTo("/oauth/token")).willReturn(
        okJson("{\"access_token\":\"oauth-token\"}")
      )
    );
    server.stubFor(
      get(urlEqualTo("/resource"))
        .withHeader("Authorization", equalTo("Bearer oauth-token"))
        .willReturn(okJson("{}"))
    );
    service.call(config, "GET", "/resource", null, "test");
    server.verify(postRequestedFor(urlEqualTo("/oauth/token")));
  }

  @Test
  void approvalIsConsumedAndConfigurationBound() {
    server.stubFor(
      post(urlEqualTo("/v3/organizations/demo/sessions")).willReturn(
        okJson("{\"session_id\":\"session-1\"}")
      )
    );
    var a = store.parse(
      "{\"method\":\"POST\",\"path\":\"/v3/organizations/demo/sessions\",\"body\":{\"prompt\":\"Review API\"}}"
    );
    var e = service.propose(config.path("id").asText(), a, "developer");
    String id = e.path("id").asText();
    assertThrows(Exception.class, () -> service.execute(id, "test"));
    service.approve(id, "reviewer");
    assertEquals(
      "session-1",
      service.execute(id, "test").path("session_id").asText()
    );
    assertThrows(Exception.class, () -> service.execute(id, "test"));
    var next = service.propose(config.path("id").asText(), a, "test");
    service.approve(next.path("id").asText(), "reviewer");
    config.put("name", "Changed");
    config = service.save(config, "test");
    assertThrows(Exception.class, () ->
      service.execute(next.path("id").asText(), "test")
    );
  }

