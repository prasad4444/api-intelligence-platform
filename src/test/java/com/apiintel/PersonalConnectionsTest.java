  @Test
  void personalSignInConnectDiscoverSaveRestartReplayWithoutBrowser() throws Exception {
    server.stubFor(get(urlEqualTo("/user")).willReturn(okJson("{\"login\":\"alice-gh\"}")));
    server.stubFor(get(urlEqualTo("/api/items")).willReturn(okJson("{\"items\":[1]}")));

    var connected = connections.connect(store.parse("{}")
      .put("provider", "github")
      .put("name", "Alice GitHub")
      .put("baseUrl", server.baseUrl())
      .put("authType", "BEARER")
      .put("credential", "alice-token"), "alice");
    assertEquals("CONNECTED", connected.path("state").asText());
    assertEquals("alice-gh", connected.path("verifiedIdentity").asText());
    assertTrue(vault.get("alice-token").isBlank());
    assertFalse(vault.getScoped(aliceId, connected.path("id").asText(), "credential").isBlank());

    var session = discovery.start(store.parse("{}")
      .put("connectionId", connected.path("id").asText())
      .put("url", server.baseUrl() + "/app")
      .put("interactive", false), "alice");
    assertEquals("COMPLETED", session.path("status").asText());
    assertEquals(1, session.path("captures").size());

    var saved = discovery.saveSelected(session.path("id").asText(),
      store.parse("{\"indexes\":[0]}"), "alice");
    String captureId = saved.path("saved").get(0).path("id").asText();

    // Simulate process restart with the same SQLite/H2 data by reconstructing services on the same DB.
    var guard = org.mockito.Mockito.mock(NetworkGuard.class);
    org.mockito.Mockito.when(guard.validate(org.mockito.ArgumentMatchers.anyString()))
      .thenAnswer(a -> java.net.URI.create(a.getArgument(0)));
    var approved2 = new ApprovedHosts(store, guard, "", "", "http://localhost:18080");
    var integrations2 = new IntegrationService(store, vault, guard, approved2, "http://localhost:18080");
    var connections2 = new ConnectionService(store, vault, users, integrations2, approved2);
    var replay2 = new ReplayService(store, vault, connections2, approved2);
    asUser("alice", "DEVELOPER");
    var result = replay2.replay(captureId, store.parse("{}"), "alice");
    assertEquals(200, result.path("upstreamStatus").asInt());
    assertEquals(false, result.path("browserUsed").asBoolean());
    assertEquals(1, result.path("data").path("items").get(0).asInt());
    assertFalse(replay2.browserStartedDuringReplay());
  }

