  @Test
  void sqliteFileUpgradeKeepsLegacySecrets() throws Exception {
    var dir = Files.createTempDirectory("apiintel-upgrade");
    var file = dir.resolve("platform.sqlite");
    var ds = new DriverManagerDataSource("jdbc:sqlite:" + file, "", "");
    var sqlite = new JdbcTemplate(ds);
    sqlite.execute("CREATE TABLE secrets(name TEXT PRIMARY KEY, ciphertext TEXT NOT NULL)");
    sqlite.execute("CREATE TABLE scoped_secrets(owner_id TEXT, connection_id TEXT, name TEXT, ciphertext TEXT, PRIMARY KEY(owner_id,connection_id,name))");
    var legacyVault = new Vault(sqlite, "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=");
    legacyVault.put("github-token", "legacy-shared");
    assertEquals("legacy-shared", legacyVault.get("github-token"));
    legacyVault.putScoped("owner-1", "conn-1", "credential", "personal");
    assertEquals("personal", legacyVault.getScoped("owner-1", "conn-1", "credential"));
    assertEquals("legacy-shared", legacyVault.get("github-token"));
  }

  private void asUser(String username, String role) {
    SecurityContextHolder.getContext().setAuthentication(
      new UsernamePasswordAuthenticationToken(username, "x", List.of(new SimpleGrantedAuthority("ROLE_" + role)))
    );
  }
