  @Test
  void disconnectInvalidatesSecretsAndPendingWork() {
    server.stubFor(get(urlEqualTo("/user")).willReturn(okJson("{\"login\":\"alice-gh\"}")));
    var alice = connections.connect(store.parse("{}")
      .put("provider", "github").put("name", "A").put("baseUrl", server.baseUrl())
      .put("authType", "BEARER").put("credential", "alice-secret"), "alice");
    var runtime = connections.runtimeConfig(connections.getOwned(alice.path("id").asText(), "alice"));
    var event = integrations.propose(runtime.path("id").asText(),
      store.parse("{\"method\":\"POST\",\"path\":\"/repos/o/r/git/refs\",\"body\":{}}"), "alice");
    assertEquals("PENDING", event.path("status").asText());
    connections.disconnect(alice.path("id").asText(), "alice");
    assertTrue(vault.getScoped(aliceId, alice.path("id").asText(), "credential").isBlank());
    assertEquals("CANCELLED", store.get("events", event.path("id").asText()).path("status").asText());
  }

